"""Turn a recorded failure into a new, runnable synthetic task.

A failure memory entry carries the failing solution's minimal repro code and the
task name. `rsi.synth` copies the source task, gives it a new identity, writes it
under `tasks/synth/`, and validates that an honest reference solution passes.
Synthetic tasks are approval-gated: the sidecar JSON starts with approved=false
unless `--approve` is given.

    python -m rsi.synth --failures rsi/knowledge/failures.jsonl --out tasks/synth
    python -m rsi.synth --failures rsi/knowledge/failures.jsonl --out tasks/synth --approve
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import inspect
import json
import os
import re
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from harness.runner import run_evaluation  # noqa: E402
from harness.tasks import load_task  # noqa: E402

DEFAULT_FAILURES = os.path.join(ROOT, "rsi", "knowledge", "failures.jsonl")
DEFAULT_OUT = os.path.join(ROOT, "tasks", "synth")
DEFAULT_TASKS = os.path.join(ROOT, "tasks")


def _read_jsonl(path: str) -> list:
    rows = []
    if not os.path.isfile(path):
        return rows
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except ValueError:
                    continue
    return rows


def _find_source_task(tasks_root: str, name: str):
    for path in sorted(glob.glob(os.path.join(tasks_root, "**", "*.py"), recursive=True)):
        if "__pycache__" in path or os.path.basename(path).startswith("_"):
            continue
        try:
            task = load_task(path)
        except Exception:
            continue
        if task.name == name:
            return path, task
    return None, None


def _synth_name(source_name: str, failure: dict) -> str:
    seed = str(failure.get("signature_hash") or failure.get("id") or failure.get("signature") or "failure")
    digest = hashlib.sha256(seed.encode("utf-8")).hexdigest()[:8]
    return "synth_%s_%s" % (re.sub(r"[^A-Za-z0-9_]", "_", source_name), digest)


def _synthesize_source(source: str, source_name: str, synth_name: str, failure: dict) -> str:
    new = re.sub(r'("name"\s*:\s*")' + re.escape(source_name) + r'(")',
                 lambda m: m.group(1) + synth_name + m.group(2), source, count=1)
    meta = ('"synthetic": True, "source_task": %s, "failure_signature": %s,\n    '
            % (json.dumps(source_name), json.dumps(str(failure.get("signature") or ""))))
    new = new.replace("TASK = {", "TASK = {\n    " + meta, 1)
    header = ('"""Synthetic task generated by rsi.synth from a real failure.\n\n'
              'source task: %s\nfailure: %s\n\nNot a performance claim; generated for practice.\n"""\n'
              % (source_name, str(failure.get("signature") or "")[:200]))
    return header + new


def _reference_solution(task) -> str:
    """A solution that is a faithful copy of the task's reference implementation."""
    reference = inspect.getsource(task.module.reference)
    reference = re.sub(r"^def\s+reference\s*\(", "def run(", reference, count=1, flags=re.M)
    head = task.source.split("TASK = {", 1)[0]
    return head + "\n" + reference + "\n"


def _validate(task_path: str, solution: str, device: str, timeout: float) -> dict:
    tmp = tempfile.mkdtemp(prefix="synth-validate-")
    solution_path = os.path.join(tmp, "reference_solution.py")
    with open(solution_path, "w", encoding="utf-8") as fh:
        fh.write(solution)
    result = run_evaluation(
        task=task_path, solution=solution_path, device=device, timeout=timeout,
        out_dir=os.path.join(tmp, "out"), results_file=os.path.join(tmp, "results.jsonl"),
        append=False, quiet=True, holdout=False,
    )
    return {
        "status": result.get("status"),
        "speedup": (result.get("timing") or {}).get("speedup"),
        "ok": result.get("status") in ("pass", "pass_unstable"),
        "error": result.get("error"),
    }


def synthesize(failures: list, tasks_root: str, out_dir: str, approve: bool,
               device: str, timeout: float, limit: int) -> list:
    os.makedirs(out_dir, exist_ok=True)
    report = []
    for failure in failures[:max(0, int(limit))]:
        repro = failure.get("minimal_repro") or {}
        code = str(repro.get("code") or "").strip()
        task_name = str(repro.get("task") or failure.get("task") or "").strip()
        if not code or not task_name:
            report.append({"failure": failure.get("id"), "status": "skipped",
                           "reason": "failure has no minimal repro code/task"})
            continue
        source_path, source_task = _find_source_task(tasks_root, task_name)
        if not source_task:
            report.append({"failure": failure.get("id"), "status": "skipped",
                           "reason": "source task not found: %s" % task_name})
            continue
        synth_name = _synth_name(source_task.name, failure)
        task_path = os.path.join(out_dir, synth_name + ".py")
        if os.path.isfile(task_path):
            report.append({"failure": failure.get("id"), "status": "exists",
                           "task": synth_name, "path": task_path})
            continue
        source = _synthesize_source(source_task.source, source_task.name, synth_name, failure)
        with open(task_path, "w", encoding="utf-8") as fh:
            fh.write(source)
        solution = _reference_solution(source_task)
        validation = _validate(task_path, solution, device, timeout)
        sidecar = os.path.splitext(task_path)[0] + ".json"
        record = {
            "task": synth_name,
            "synthetic": True,
            "source_task": source_task.name,
            "source_task_path": os.path.relpath(source_path, ROOT).replace("\\", "/"),
            "failure_id": failure.get("id"),
            "failure_signature": failure.get("signature"),
            "minimal_repro_code": code[:4000],
            "approved": bool(approve and validation.get("ok")),
            "validation": validation,
        }
        if not validation.get("ok"):
            os.remove(task_path)
            record["status"] = "rejected"
            record["path"] = ""
        else:
            record["status"] = "created"
            record["path"] = task_path
        with open(sidecar, "w", encoding="utf-8") as fh:
            json.dump(record, fh, ensure_ascii=False, indent=2)
        report.append(record)
    return report


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="rsi.synth", description="Generate synthetic tasks from failure memory.")
    ap.add_argument("--failures", default=DEFAULT_FAILURES)
    ap.add_argument("--tasks-root", default=DEFAULT_TASKS)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--limit", type=int, default=5)
    ap.add_argument("--approve", action="store_true", help="approve created tasks for scheduling")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--timeout", type=float, default=900.0)
    args = ap.parse_args(argv)

    rows = synthesize(_read_jsonl(args.failures), args.tasks_root, args.out,
                      args.approve, args.device, args.timeout, args.limit)
    print(json.dumps({"generated": rows}, ensure_ascii=False, indent=2))
    return 0 if any(row.get("status") == "created" for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
